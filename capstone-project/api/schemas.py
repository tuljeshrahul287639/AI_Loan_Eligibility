from typing import Literal, Optional

from pydantic import BaseModel, Field

EmploymentType = Literal["Full-time", "Part-time", "Self-employed"]


class LoanApplicationIn(BaseModel):
    """Loan application payload. Field names match data/sample_applications.json."""

    applicant_id: Optional[str] = Field(None, description="Generated by the server if omitted")
    name: str = Field(..., min_length=1, max_length=120)
    monthly_income: float = Field(..., ge=0)
    monthly_expenses: float = Field(..., ge=0)
    credit_score: int = Field(..., ge=300, le=850)
    loan_amount: float = Field(..., gt=0)
    existing_debts: float = Field(..., ge=0)
    years_employed: int = Field(..., ge=0)
    employment_type: EmploymentType
    prior_delinquencies: int = Field(0, ge=0)
    bankruptcy_history: bool = False
    recent_inquiries: int = Field(0, ge=0)


class ApplicationSubmit(LoanApplicationIn):
    """Final application submitted from the upload form, optionally linked to uploaded documents."""

    document_ids: list[int] = Field(default_factory=list)
